#Вариант 4
import json  # импортируем модуль для работы с json файлами
import os  # импортируем модуль для работы с операционной системой

filename = "cars.json"  # задаем имя файла для хранения данных

operations_count = 0  # создаем счетчик операций с данными

if not os.path.exists(filename):  # проверяем существует ли файл с данными
    initial_data = [  # создаем начальные данные для базы
        {"id": 1, "name": "Corolla", "manufacturer": "Toyota", "is_petrol": True, "tank_volume": 43},
        {"id": 2, "name": "Civic", "manufacturer": "Honda", "is_petrol": True, "tank_volume": 47},
        {"id": 3, "name": "Model 3", "manufacturer": "Tesla", "is_petrol": False, "tank_volume": 0},
        {"id": 4, "name": "X5", "manufacturer": "BMW", "is_petrol": True, "tank_volume": 83},
        {"id": 5, "name": "Focus", "manufacturer": "Ford", "is_petrol": True, "tank_volume": 52}
    ]
    with open(filename, 'w', encoding='utf-8') as file:  # открываем файл для записи
        json.dump(initial_data, file, ensure_ascii=False, indent=2)  # записываем начальные данные в файл
    operations_count += 1  # увеличиваем счетчик операций

while True:  # начинаем бесконечный цикл программы
    print("\n" + "=" * 40)  # выводим разделительную линию
    print("МЕНЮ УПРАВЛЕНИЯ БАЗОЙ ДАННЫХ АВТОМОБИЛЕЙ")  # выводим заголовок меню
    print("=" * 40)  # выводим разделительную линию
    print("1. вывести все записи")  # выводим пункт меню 1
    print("2. вывести запись по полю id")  # выводим пункт меню 2
    print("3. добавить запись")  # выводим пункт меню 3
    print("4. удалить запись по полю id")  # выводим пункт меню 4
    print("5. выйти из программы")  # выводим пункт меню 5
    print("=" * 40)  # выводим разделительную линию
    
    choice = input("выберите пункт меню (1-5): ").strip()  # запрашиваем выбор пользователя и удаляем пробелы
    
    if choice == "1":  # если выбран пункт 1
        try:  # начинаем блок обработки исключений
            with open(filename, 'r', encoding='utf-8') as file:  # открываем файл для чтения
                cars = json.load(file)  # загружаем данные из файла
            
            if not cars:  # проверяем пустая ли база данных
                print("\nбаза данных пуста.")  # выводим сообщение о пустой базе
            else:  # если база не пустая
                print(f"\n{'='*60}")  # выводим разделительную линию
                print(f"ВСЕ ЗАПИСИ В БАЗЕ ДАННЫХ (всего: {len(cars)})")  # выводим заголовок с количеством записей
                print('='*60)  # выводим разделительную линию
                for i, car in enumerate(cars, 1):  # перебираем все записи с нумерацией
                    fuel_type = "бензин" if car.get("is_petrol", False) else "электричество"  # определяем тип топлива
                    tank = f"{car.get('tank_volume', 0)} л" if car.get("is_petrol", False) else "нет бака"  # форматируем объем бака
                    print(f"{i}. id: {car.get('id', 'N/A')}")  # выводим id записи
                    print(f"   модель: {car.get('name', 'не указано')}")  # выводим название модели
                    print(f"   производитель: {car.get('manufacturer', 'не указано')}")  # выводим производителя
                    print(f"   тип топлива: {fuel_type}")  # выводим тип топлива
                    print(f"   объем бака: {tank}")  # выводим объем бака
                    print(f"   {'-'*40}")  # выводим разделительную линию между записями
            operations_count += 1  # увеличиваем счетчик операций
            
        except Exception as e:  # если произошла ошибка
            print(f"\nошибка при чтении файла: {e}")  # выводим сообщение об ошибке
    
    elif choice == "2":  # если выбран пункт 2
        try:  # начинаем блок обработки исключений
            search_id = input("введите id для поиска: ").strip()  # запрашиваем id для поиска
            if not search_id.isdigit():  # проверяем является ли ввод числом
                print("\nошибка: id должен быть числом.")  # выводим сообщение об ошибке
                continue  # переходим к следующей итерации цикла
            
            search_id = int(search_id)  # преобразуем ввод в целое число
            
            with open(filename, 'r', encoding='utf-8') as file:  # открываем файл для чтения
                cars = json.load(file)  # загружаем данные из файла
            
            found = False  # флаг для отслеживания найденной записи
            for i, car in enumerate(cars):  # перебираем все записи
                if car.get("id") == search_id:  # сравниваем id записи с искомым
                    print(f"\n{'='*60}")  # выводим разделительную линию
                    print(f"НАЙДЕНА ЗАПИСЬ (позиция в базе: {i+1})")  # выводим заголовок с позицией записи
                    print('='*60)  # выводим разделительную линию
                    fuel_type = "бензин" if car.get("is_petrol", False) else "электричество"  # определяем тип топлива
                    tank = f"{car.get('tank_volume', 0)} л" if car.get("is_petrol", False) else "нет бака"  # форматируем объем бака
                    print(f"id: {car.get('id', 'N/A')}")  # выводим id записи
                    print(f"модель: {car.get('name', 'не указано')}")  # выводим название модели
                    print(f"производитель: {car.get('manufacturer', 'не указано')}")  # выводим производителя
                    print(f"тип топлива: {fuel_type}")  # выводим тип топлива
                    print(f"объем бака: {tank}")  # выводим объем бака
                    found = True  # устанавливаем флаг найденной записи
                    break  # прерываем цикл поиска
            
            if not found:  # если запись не найдена
                print(f"\nзапись с id={search_id} не найдена.")  # выводим сообщение о ненайденной записи
            
            operations_count += 1  # увеличиваем счетчик операций
            
        except Exception as e:  # если произошла ошибка
            print(f"\nошибка при поиске записи: {e}")  # выводим сообщение об ошибке
    
    elif choice == "3":  # если выбран пункт 3
        try:  # начинаем блок обработки исключений
            with open(filename, 'r', encoding='utf-8') as file:  # открываем файл для чтения
                cars = json.load(file)  # загружаем данные из файла
            
            max_id = 0  # переменная для хранения максимального id
            for car in cars:  # перебираем все записи
                current_id = car.get("id", 0)  # получаем id текущей записи
                if current_id > max_id:  # сравниваем с максимальным
                    max_id = current_id  # обновляем максимальный id
            
            new_id = max_id + 1  # вычисляем id для новой записи
            
            print(f"\nдобавление новой записи (id будет присвоен: {new_id})")  # выводим информационное сообщение
            print('-' * 40)  # выводим разделительную линию
            
            name = input("введите название модели: ").strip()  # запрашиваем название модели
            manufacturer = input("введите производителя: ").strip()  # запрашиваем производителя
            
            is_petrol_input = input("заправляется бензином? (да/нет): ").strip().lower()  # запрашиваем тип топлива
            is_petrol = is_petrol_input in ['да', 'д', 'yes', 'y']  # определяем булево значение
            
            tank_volume = 0  # переменная для объема бака
            if is_petrol:  # если машина на бензине
                tank_input = input("введите объем бака в литрах: ").strip()  # запрашиваем объем бака
                try:  # пытаемся преобразовать ввод
                    tank_volume = float(tank_input)  # преобразуем в число с плавающей точкой
                    if tank_volume <= 0:  # проверяем положительное ли число
                        print("объем бака должен быть положительным числом. установлено значение 40 л.")  # сообщение об ошибке
                        tank_volume = 40.0  # устанавливаем значение по умолчанию
                except ValueError:  # если ввод не число
                    print("неверный формат числа. установлено значение 40 л.")  # сообщение об ошибке
                    tank_volume = 40.0  # устанавливаем значение по умолчанию
            
            new_car = {  # создаем словарь для новой записи
                "id": new_id,  # id записи
                "name": name if name else "не указано",  # название модели или значение по умолчанию
                "manufacturer": manufacturer if manufacturer else "не указано",  # производитель или значение по умолчанию
                "is_petrol": is_petrol,  # тип топлива
                "tank_volume": tank_volume  # объем бака
            }
            
            cars.append(new_car)  # добавляем новую запись в список
            
            with open(filename, 'w', encoding='utf-8') as file:  # открываем файл для записи
                json.dump(cars, file, ensure_ascii=False, indent=2)  # записываем обновленные данные в файл
            
            print(f"\nзапись успешно добавлена с id={new_id}")  # выводим сообщение об успешном добавлении
            operations_count += 1  # увеличиваем счетчик операций
            
        except Exception as e:  # если произошла ошибка
            print(f"\nошибка при добавлении записи: {e}")  # выводим сообщение об ошибке
    
    elif choice == "4":  # если выбран пункт 4
        try:  # начинаем блок обработки исключений
            delete_id = input("введите id записи для удаления: ").strip()  # запрашиваем id для удаления
            if not delete_id.isdigit():  # проверяем является ли ввод числом
                print("\nошибка: id должен быть числом.")  # выводим сообщение об ошибке
                continue  # переходим к следующей итерации цикла
            
            delete_id = int(delete_id)  # преобразуем ввод в целое число
            
            with open(filename, 'r', encoding='utf-8') as file:  # открываем файл для чтения
                cars = json.load(file)  # загружаем данные из файла
            
            original_count = len(cars)  # сохраняем исходное количество записей
            cars = [car for car in cars if car.get("id") != delete_id]  # фильтруем записи, исключая удаляемую
            
            if len(cars) == original_count:  # если количество записей не изменилось
                print(f"\nзапись с id={delete_id} не найдена.")  # выводим сообщение о ненайденной записи
            else:  # если запись была удалена
                with open(filename, 'w', encoding='utf-8') as file:  # открываем файл для записи
                    json.dump(cars, file, ensure_ascii=False, indent=2)  # записываем обновленные данные в файл
                print(f"\nзапись с id={delete_id} успешно удалена.")  # выводим сообщение об успешном удалении
            
            operations_count += 1  # увеличиваем счетчик операций
            
        except Exception as e:  # если произошла ошибка
            print(f"\nошибка при удалении записи: {e}")  # выводим сообщение об ошибке
    
    elif choice == "5":  # если выбран пункт 5
        print(f"\n{'='*60}")  # выводим разделительную линию
        print(f"ВЫХОД ИЗ ПРОГРАММЫ")  # выводим заголовок выхода
        print('='*60)  # выводим разделительную линию
        print(f"всего выполнено операций: {operations_count}")  # выводим количество выполненных операций
        print("до свидания!")  # выводим прощальное сообщение
        print('='*60)  # выводим разделительную линию
        break  # прерываем бесконечный цикл (выход из программы)
    
    else:  # если выбран неверный пункт меню
        print("\nошибка: выберите пункт от 1 до 5.")  # выводим сообщение об ошибке

print("end code")  # выводим сообщение о завершении выполнения кода
#дмитрук яны
print ("start code")  # выводим сообщение о начале выполнения кода

import json  # подключаем модуль для работы с json файлами

try:  # начинаем блок обработки ошибок
    with open('dump.json', 'r', encoding='utf-8') as file:  # открываем файл для чтения
        all_data = json.load(file)  # загружаем данные из json файла
    
    skills = []  # создаем пустой список для квалификаций
    
    for item in all_data:  # перебираем все элементы данных
        if isinstance(item, dict) and item.get('model') == 'data.skill':  # проверяем нужный тип элемента
            skills.append(item)  # добавляем подходящий элемент в список
    
    if not skills:  # если список пустой
        print("не удалось загрузить данные квалификаций.")  # выводим сообщение об ошибке
        exit()  # завершаем программу

except FileNotFoundError:  # если файл не найден
    print("ошибка: файл 'dump.json' не найден.")  # сообщаем об ошибке
    exit()  # завершаем программу
except json.JSONDecodeError:  # если json некорректный
    print("ошибка: файл 'dump.json' содержит некорректный json.")  # сообщаем об ошибке
    exit()  # завершаем программу
except Exception as e:  # для всех других ошибок
    print(f"ошибка при чтении файла: {e}")  # выводим информацию об ошибке
    exit()  # завершаем программу

qual_code = input("введите номер квалификации (например, 4-02-0413-01): ").strip()  # запрашиваем код у пользователя

found_skill = None  # переменная для найденной квалификации

for skill in skills:  # перебираем все квалификации
    fields = skill.get('fields', {})  # получаем словарь fields
    code = fields.get('code', '')  # получаем код квалификации
    
    if code == qual_code:  # сравниваем с введенным кодом
        found_skill = skill  # сохраняем найденную квалификацию
        break  # прерываем поиск

if not found_skill:  # если квалификация не найдена
    print("=============== не найдено ===============")  # выводим сообщение
else:  # если квалификация найдена
    fields = found_skill.get('fields', {})  # получаем fields найденной квалификации
    code = fields.get('code', '')  # получаем код
    name = fields.get('name', '')  # получаем название
    short_name = fields.get('short_name', '')  # получаем короткое название
    
    parts = code.split('-')  # разбиваем код на части
    
    print("=============== найдено ===============")  # выводим заголовок
    
    if len(parts) == 4:  # если код из 4 частей (специальность)
        print(f'{code} >> специальность "{name}", {short_name}')  # выводим информацию о специальности
    elif len(parts) == 5:  # если код из 5 частей (квалификация)
        print(f'{code} >> квалификация "{name}"')  # выводим информацию о квалификации
    else:  # для других форматов
        print(f'{code} >> {name}')  # выводим общую информацию

print("end code")  # выводим сообщение о завершении выполнения кода